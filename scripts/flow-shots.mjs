// Captures the buy flow: node scripts/flow-shots.mjs <base> <outDir> <width>
import { chromium } from "@playwright/test";
import { mkdirSync } from "node:fs";
const [base, out, w = "390"] = process.argv.slice(2);
const width = Number(w);
mkdirSync(out, { recursive: true });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width, height: width < 768 ? 844 : 900 }, deviceScaleFactor: width < 768 ? 2 : 1, isMobile: width < 768, hasTouch: width < 768 });
const p = await ctx.newPage();
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
p.on("console", (m) => m.type() === "error" && !/404|WebSocket/.test(m.text()) && errs.push(m.text()));
const shot = async (name) => { await p.waitForTimeout(1200); await p.screenshot({ path: `${out}/${name}-${width}.png` }); console.log("saved", name); };
await p.goto(`${base}/login?next=/products/party-jollof-and-chicken-mamaputexpress`);
await p.getByRole("button", { name: /try the demo buyer/i }).click();
await p.waitForURL(/products/);
await p.getByRole("button", { name: /Add to bag/ }).filter({ visible: true }).first().click();
await p.goto(`${base}/products/wireless-earbuds-pro-plughub`);
await p.getByRole("button", { name: /Add to bag/ }).filter({ visible: true }).first().click();
await p.waitForTimeout(900);
await p.goto(`${base}/bag`); await shot("bag");
await p.goto(`${base}/checkout`); await p.getByLabel("Promo code").first().waitFor(); await shot("checkout");
await p.getByLabel("Promo code").first().fill("KIOSK10");
await p.getByRole("button", { name: "Apply" }).first().click();
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/checkout-full-${width}.png`, fullPage: true });
await p.getByLabel("Room, block or landmark").nth(1).fill("Room 12, Block C");
await p.getByRole("button", { name: /Place 2 orders/ }).filter({ visible: true }).first().click();
await p.waitForURL(/success/); await shot("success");
await p.getByRole("link", { name: /Track your orders/ }).click();
await p.waitForURL(/\/orders$/); await shot("orders");
await p.getByRole("link", { name: /Mama Put Express/ }).first().click();
await p.waitForURL(/orders\/o_/);
await p.waitForTimeout(36000); await shot("tracking");
await b.close();
console.log(errs.length ? "ERRORS:\n" + errs.join("\n") : "No console errors.");
